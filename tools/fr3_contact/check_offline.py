CONFIG = BENCH / 'configs/special_scene_vmc_readout06_20261028.json'
SOURCES = [BENCH/'scripts/run_vmc_6d_constrained_push_20260918.py',
           BENCH/'scripts/vmc_teacher_stable_readout_20260930.py',
           BENCH/'tools/optimize_tool_contact_20261002.py']

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def original_class():
    scope = {'np': np}
    for path, names in zip(SOURCES, [('virtual_frame', 'SixDVirtualDynamics'),
                                    ('StableReadoutTeacher',), ('ParameterTeacher',)], strict=True):
        tree = ast.parse(path.read_text())
        nodes = [n for n in tree.body if isinstance(n, (ast.ClassDef, ast.FunctionDef)) and n.name in names]
        assert len(nodes) == len(names)
        exec(compile(ast.Module(body=nodes, type_ignores=[]), str(path), 'exec'), scope)
    return scope['ParameterTeacher']

def profile_text(cls):
    config = json.loads(CONFIG.read_text())
    # This port intentionally supports exactly the selected active-recovery profile.
    assert set(config) == {'recovery', 'velocity_weight', 'pair_average'}
    assert config['pair_average'] is True
    assert config['recovery']['activation_mode'] == 'progress'
    assert set(config['recovery']) == {'threshold_n','attack_s','release_s','offset_m',
                                    'gain_per_s','velocity_mps','activation_mode','progress_distance_m'}
    actor = cls(config)
    np.testing.assert_array_equal(actor.R6, np.eye(6))
    np.testing.assert_array_equal(actor.channel_gain, np.ones(7))
    lines = ['// Generated by check_offline.py --generate-profile; do not hand edit.',
             '// Selected active recovery profile, NOT a hardware qualification.',
             f'inline constexpr char kProfileSha[]="{sha(CONFIG)}";']
    for name, value in [('Stiffness',actor.k),('Damping',actor.b),('Mass',actor.mass),
                        ('Sigma',actor.sigma),('Deadband',actor.deadband),('Vmax',actor.vmax),
                        ('Xmax',actor.xmax),('ActionLimits',actor.action_limits)]:
        lines.append('inline constexpr double k'+name+'[6]={'+','.join(format(float(x),'.17g') for x in value)+'};')
    scalars = {'FilterTau':actor.filter_tau,'VelocityWeight':actor.velocity_weight,'OffsetGain':actor.offset_gain}
    for name,key in [('Threshold','threshold_n'),('Attack','attack_s'),('Release','release_s'),
                     ('Offset','offset_m'),('Gain','gain_per_s'),('Velocity','velocity_mps'),('Distance','progress_distance_m')]:
        scalars['Recovery'+name]=config['recovery'][key]
    for name,value in scalars.items():lines.append(f'inline constexpr double k{name}={value:.17g};')
    return '\n'.join(lines)+'\n'

def fixtures(cls):
    rng=np.random.default_rng(20261115)
    rows=[]
    # Zero, sustained opposing push, release, changing direction, strong saturation and repeat.
    for i in range(1800):
        obs=np.zeros(48)
        if 100<=i<400:
            obs[14]=.025;obs[26]=.025;obs[45]=1;obs[39]=-5
        elif 400<=i<650:
            obs[14]=.025;obs[26]=.005;obs[45]=1;obs[22]=-.015
        elif 650<=i<1500:
            obs=rng.normal(size=48)*.02
            obs[39:45]=rng.normal(size=6)*np.array([4,4,4,.5,.5,.5])
            direction=rng.normal(size=3);obs[45:48]=direction/np.linalg.norm(direction)
        elif i>=1500:
            obs[39:45]=[300,-200,150,15,-20,30]
            obs[14]=.03;obs[26]=.03;obs[45]=1
        rows.append(obs)
    actor=cls(json.loads(CONFIG.read_text()));expected=[]
    for obs in rows:
        actor.observe(obs);action=actor.act(obs[39:45],.04)
        expected.append(np.r_[action,actor.offset,actor.velocity,actor.filtered,actor.recovery_memory])
    assert np.max(np.array(expected)[:, -1])>.5  # actually exercises recovery, not only idle
    return np.array(rows),np.array(expected)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--generate-profile',action='store_true')
    parser.add_argument('--evidence',type=Path)
    parser.add_argument('--sanitize',action='store_true')
    args=parser.parse_args()
    child_environment=os.environ.copy()
    if args.sanitize:
        # LSan cannot run under this host's ptrace sandbox. ASan/UBSan remain enabled.
        child_environment['ASAN_OPTIONS']=child_environment.get('ASAN_OPTIONS','')+':detect_leaks=0'
    def checked_run(argv, **kwargs):
        completed=subprocess.run(argv,capture_output=True,text=True,env=child_environment,**kwargs)
        if completed.returncode:
            message=f'Command failed ({completed.returncode}): {argv}\n{completed.stdout}\n{completed.stderr}'
            if args.evidence:
                for index in range(1,100):
                    failure=args.evidence.with_suffix(f'.failure{index}.txt')
                    if not failure.exists():
                        with failure.open('x') as f:f.write(message)
                        break
            raise RuntimeError(message)
        return completed
    def forbidden(*a,**k):raise AssertionError('network forbidden in offline test')
    socket.socket=forbidden
    cls=original_class()
    generated=profile_text(cls)
    profile=HERE/'profile_generated.inc'
    if args.generate_profile:
        profile.write_text(generated)
        print('Generated fixed active-recovery profile; no hardware access.')
        return
    if profile.read_text()!=generated:raise RuntimeError('Profile/source drift: regenerate and review')
    with tempfile.TemporaryDirectory(prefix='fr3-vmc-offline-') as tmp:
        tmp=Path(tmp);exe=tmp/'offline_test'
        flags=['g++','-std=c++17','-O2','-Wall','-Wextra','-Werror','-DEIGEN_RUNTIME_NO_MALLOC',
               '-isystem','/usr/include/eigen3','-I'+str(HERE)]
        if args.sanitize:
            flags[2]='-O1'
            flags+=['-fsanitize=address,undefined','-fno-omit-frame-pointer']
        build=flags+[str(HERE/'offline_test.cpp'),'-o',str(exe),'-lfranka']
        checked_run(build)
        # Compile the real model/callback seam without connecting to a Robot.
        checked_run(flags+['-x','c++','-c','-o',str(tmp/'adapter.o'),'-'],
                    input='#include "reviewed_session.hpp"\n')
        reject=subprocess.run([str(exe),'172.16.0.2'],capture_output=True,text=True,env=child_environment)
        assert reject.returncode!=0 and 'offline tests only' in reject.stderr
        result=checked_run([str(exe)])
        rows,expected=fixtures(cls)
        inputs=tmp/'input.txt';np.savetxt(inputs,rows,fmt='%.17g')
        parity=checked_run([str(exe),'--actor-fixture',str(inputs)])
        actual=np.loadtxt(parity.stdout.splitlines())
        np.testing.assert_allclose(actual,expected,rtol=1e-11,atol=1e-12)
        maximum=float(np.max(np.abs(actual-expected)))
        audit={'hardware_connected':False,'motion_started':False,'robot_parameters_written':False,
               'hardware_qualified':False,'live_launcher_present':False,
               'address_argument_rejected':True,'sanitizers':args.sanitize,
               'leak_sanitizer_enabled':False,
               'profile':str(CONFIG.relative_to(ROOT)),'profile_sha256':sha(CONFIG),
               'actor_fixture_steps':len(rows),'actor_max_absolute_error':maximum,
               'recovery_max_activation':float(expected[:,-1].max()),
               'tests_stdout':result.stdout,'compiler_flags':flags,
               'source_sha256':{str(p.relative_to(ROOT)):sha(p) for p in SOURCES+[CONFIG]+sorted(HERE.glob('*.hpp'))+
                                 [HERE/'profile_generated.inc',HERE/'offline_test.cpp',Path(__file__).resolve()]},
               'limitations':['synthetic fake-plant checks, not contact dynamics certification',
                              'external wrench sign/frame and real-time deadlines need physical validation',
                              'stationary adapter has zero path intent; moving active recovery tested only with synthetic actor/core inputs',
                              'application limits proposed offline; no device collision thresholds changed']}
        if args.evidence:
            with args.evidence.open('x') as f:json.dump(audit,f,indent=2,allow_nan=False);f.write('\n')
        print(result.stdout.strip());print('Original Python vs C++ max difference:',maximum)
        print('Offline checks complete; NOT hardware qualified.')

if __name__=='__main__':main()
